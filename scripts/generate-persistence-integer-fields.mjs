import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const base = join(root, "desktop/src/stickvania");
const classes = new Map();
for (const name of readdirSync(base)
    .filter((name) => name.endsWith(".java"))
    .sort()) {
    const source = readFileSync(join(base, name), "utf8").replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, "");
    const declaration = /\bclass\s+(\w+)(?:\s+extends\s+(\w+))?/.exec(source);
    if (!declaration) continue;
    // Explicit Java scalar declarations, not suffix/default-value inference.
    // Methods, arrays, statics and locals are excluded. All Thing declarations
    // use a visibility modifier; parity/inventory tests detect schema drift.
    const integers = [...source.matchAll(/^\s*(?:public|protected|private)\s+(?!static\b)(?:final\s+)?int\s+(\w+)\s*(?=[=;])/gm)].map((match) => match[1]);
    classes.set(declaration[1], { parent: declaration[2], integers });
}
function inherited(name, visited = new Set()) {
    if (!name) return [];
    if (visited.has(name)) throw new Error(`Cyclic Java hierarchy: ${name}`);
    visited.add(name);
    const type = classes.get(name);
    if (!type) throw new Error(`Missing Java class: ${name}`);
    return [...inherited(type.parent, visited), ...type.integers];
}
function isThing(name) {
    for (let type = name; type; type = classes.get(type)?.parent) if (type === "Thing") return true;
    return false;
}
const data = Object.fromEntries(
    [...classes.keys()]
        .filter(isThing)
        .sort()
        .map((name) => [name, [...new Set(inherited(name))].sort()])
);
const path = join(root, "pwa/src/stickvania/persistence/ThingIntegerFields.generated.ts");
const output = `// Generated by scripts/generate-persistence-integer-fields.mjs from explicit Java declarations.\n// No gameplay bounds or enum values are inferred.\nexport const THING_INTEGER_FIELDS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(data, null, 4)};\n`;
// Compare semantic data so formatting does not make --check brittle.
if (process.argv.includes("--check")) {
    const previous = readFileSync(path, "utf8").match(/=\s*([\s\S]*);\s*$/)?.[1];
    const ast = previous && ts.createSourceFile("data.ts", `const data = ${previous};`, ts.ScriptTarget.Latest, true);
    function literal(node) {
        if (ts.isStringLiteral(node)) return node.text;
        if (ts.isArrayLiteralExpression(node)) return node.elements.map(literal);
        if (ts.isObjectLiteralExpression(node))
            return Object.fromEntries(
                node.properties.map((entry) => {
                    if (!ts.isPropertyAssignment(entry) || !(ts.isIdentifier(entry.name) || ts.isStringLiteral(entry.name)))
                        throw new Error("Unsupported generated data");
                    return [entry.name.text, literal(entry.initializer)];
                })
            );
        throw new Error("Unsupported generated data");
    }
    const existing = ast && literal(ast.statements[0].declarationList.declarations[0].initializer);
    if (!existing || JSON.stringify(existing) !== JSON.stringify(data)) throw new Error("Thing integer-field declarations changed; regenerate and review.");
} else writeFileSync(path, output);
console.log(`Classified integer fields for ${Object.keys(data).length} Java Thing classes.`);
