import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";
import ts from "typescript";

const rootDir = dirname(dirname(fileURLToPath(import.meta.url)));
const resourcesPath = join(rootDir, "pwa", "src", "resources.ts");
const publicDir = join(rootDir, "pwa", "public");
const generatedTsPath = join(rootDir, "pwa", "src", "ResourceVersions.generated.ts");
const generatedJsonPath = join(rootDir, "pwa", "resource-versions.generated.json");
const checkOnly = process.argv.includes("--check");
const GLOBAL_VERSION_RESOURCES = new Set(["images/icon.png"]);

function readResourceRefs() {
    const source = ts.createSourceFile(resourcesPath, readFileSync(resourcesPath, "utf8"), ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
    for (const statement of source.statements) {
        if (!ts.isVariableStatement(statement)) continue;
        for (const declaration of statement.declarationList.declarations) {
            if (!ts.isIdentifier(declaration.name) || declaration.name.text !== "STICKVANIA_RESOURCE_REFS" || declaration.initializer === undefined) continue;
            const initializer = ts.isAsExpression(declaration.initializer) ? declaration.initializer.expression : declaration.initializer;
            if (!ts.isArrayLiteralExpression(initializer)) throw new Error("STICKVANIA_RESOURCE_REFS must remain an array literal.");
            return initializer.elements.map((element) => {
                if (!ts.isStringLiteral(element)) throw new Error("STICKVANIA_RESOURCE_REFS entries must remain string literals.");
                return element.text;
            });
        }
    }
    throw new Error("Unable to find STICKVANIA_RESOURCE_REFS.");
}

function generateVersions() {
    const versions = {};
    for (const ref of readResourceRefs()) {
        const path = join(publicDir, ...ref.split("/"));
        if (!existsSync(path)) throw new Error(`Missing PWA resource listed in STICKVANIA_RESOURCE_REFS: ${ref}`);
        if (GLOBAL_VERSION_RESOURCES.has(ref)) continue;
        versions[ref] = createHash("sha256").update(readFileSync(path)).digest("hex");
    }
    return versions;
}

const versions = generateVersions();
const json = `${JSON.stringify(versions, null, 4)}\n`;
const rawTs = `// Generated by scripts/generate-resource-versions.mjs. Do not edit by hand.\n\nexport const STICKVANIA_RESOURCE_VERSIONS = ${JSON.stringify(versions, null, 4)} as const;\n\nexport function getStickvaniaResourceVersion(ref: string): string | null {\n    return (STICKVANIA_RESOURCE_VERSIONS as Readonly<Record<string, string>>)[ref] ?? null;\n}\n`;
const prettierConfig = (await prettier.resolveConfig(generatedTsPath)) ?? {};
const formattedTs = await prettier.format(rawTs, { ...prettierConfig, parser: "typescript" });

if (checkOnly) {
    if (!existsSync(generatedJsonPath) || readFileSync(generatedJsonPath, "utf8") !== json) {
        throw new Error(`${relative(rootDir, generatedJsonPath)} is stale. Run npm run generate:resource-versions.`);
    }
    if (!existsSync(generatedTsPath) || readFileSync(generatedTsPath, "utf8") !== formattedTs) {
        throw new Error(`${relative(rootDir, generatedTsPath)} is stale. Run npm run generate:resource-versions.`);
    }
    console.log("Resource content versions are current.");
} else {
    writeFileSync(generatedJsonPath, json);
    writeFileSync(generatedTsPath, formattedTs);
    console.log(`Updated ${relative(rootDir, generatedTsPath)} and ${relative(rootDir, generatedJsonPath)}.`);
}
